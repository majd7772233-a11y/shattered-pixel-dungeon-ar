/**
 * Wire representation of a level generated by the real SPD level-generation pipeline.
 * The client exports the generated world; the server validates and stores it rather
 * than attempting to reproduce SPD's Java RNG, builders, painters and room logic in TS.
 */
public final class SPDLevelSnapshot {
    public int schemaVersion = 1;
    public int depth;
    public int branch;
    public int width;
    public int height;
    public int entrancePos;
    public int exitPos;
    public long seed;
    public boolean locked;
    public String feeling;
    /** Native Bundle with custom tilemaps/walls, mob spawn classes and respawner state. */
    public String nativeLevelMetadataBundle = "";
    public List<Integer> visitedPositions = new ArrayList<>();
    public List<Integer> mappedPositions = new ArrayList<>();
    public List<Tile> tiles = new ArrayList<>();
    public List<Transition> transitions = new ArrayList<>();
    public List<MobData> mobs = new ArrayList<>();
    public List<HeapData> heaps = new ArrayList<>();
    public List<TrapData> traps = new ArrayList<>();
    public List<BlobData> blobs = new ArrayList<>();
    public List<PlantData> plants = new ArrayList<>();
    public String heroStateJson = "";
    /** Marker/counter for a full snapshot emitted after a shared native Actor action. */
    public boolean nativeWorldTick;
    public long nativeWorldTurnCounter;
    public float nativeActorClock;
    public String nativeWorldActorKind = "";
    public int nativeWorldActorId = -1;
    public String nativeWorldActorClass = "";
    public String nativeWorldActorEntityId = "";
    public int nativeMobActorId = -1;
    public String nativeMobEntityId = "";

    public static final class Tile {
        public int pos;
        public int terrain;
        public boolean passable;
        public boolean solid;
        public boolean pit;
        public boolean losBlocking;
        public boolean flammable;
        public boolean secret;
        public boolean avoid;
        public boolean water;
        public boolean discoverable;
        public boolean openSpace;
    }

    public static final class Transition {
        public int pos;
        public String type;
        public int targetDepth;
        public int targetBranch;
        public String targetType;
    }

    public static final class MobData {
        /** Stable room/server identity; mobId remains the local SPD Actor.id(). */
        public String entityId = "";
        public int mobId;
        public String name;
        public int pos;
        public int hp;
        public int ht;
        /** Derived native shield total captured so the server can validate combat pre-state. */
        public int shielding;
        public String state;
        public String serializedBundle = "";
        public int defenseSkill;
        public float baseSpeed;
        public float effectiveSpeed;
        public float cooldown;
        public int targetCell = -1;
        public String targetType = "NONE";
        public String targetEntityId = "";
        public boolean enemySeen;
        public boolean alerted;
        public List<BuffData> buffs = new ArrayList<>();
    }

    public static final class BuffData {
        public String serializedBundle = "";
        public float cooldown;
    }

    public static final class ItemData {
        public String className;
        public int quantity;
        public int level;
        public boolean cursed;
        public boolean cursedKnown;
        public String serializedBundle = "";
    }

    public static final class HeapData {
        public int pos;
        public String type;
        public boolean seen;
        public boolean haunted;
        public boolean hidden;
        public boolean autoExplored;
        public List<ItemData> items = new ArrayList<>();
    }

    public static final class BlobData {
        public String className;
        public String serializedBundle = "";
        public float cooldown;
    }

    public static final class PlantData {
        public int pos;
        public String className;
        public String serializedBundle = "";
    }

    public static final class TrapData {
        public int pos;
        public String className;
        public boolean active;
        public boolean visible;
        public boolean reclaimed;
        public int color;
        public int shape;
        public String serializedBundle = "";
    }

    private SPDLevelSnapshot() {}

    /** Serializes a live native mob after combat so state-machine changes travel with HP. */
    public static String currentMobBundle(Mob mob) {
        if (mob == null) return "";
        Bundle mobBundle = new Bundle();
        mobBundle.put("mob", mob);
        return mobBundle.toString();
    }

    public static String currentLevelJson() {
        return buildLevelJson(null, 0L);
    }

    /** Full native world snapshot emitted only after one shared Actor finishes its native turn. */
    public static String currentNativeWorldTurnJson(Actor actor, long turnCounter) {
        if (actor == null || turnCounter < 1L || !Actor.isMultiplayerSharedActor(actor)) return null;
        return buildLevelJson(actor, turnCounter);
    }

    private static String buildLevelJson(Actor nativeWorldActor, long turnCounter) {
        Level level = Dungeon.level;
        if (level == null) return null;

        SPDLevelSnapshot out = new SPDLevelSnapshot();
        out.depth = Dungeon.depth;
        out.branch = Dungeon.branch;
        out.width = level.width();
        out.height = level.height();
        out.entrancePos = level.entrance();
        out.exitPos = level.exit();
        out.seed = Dungeon.seedCurDepth();
        out.locked = level.locked;
        out.feeling = level.multiplayerFeelingName();
        out.nativeLevelMetadataBundle = level.multiplayerMetadataBundle();
        if (nativeWorldActor != null) {
            out.nativeWorldTick = true;
            out.nativeWorldTurnCounter = turnCounter;
            out.nativeActorClock = Actor.now();
            out.nativeWorldActorId = nativeWorldActor.id();
            out.nativeWorldActorClass = nativeWorldActor.getClass().getName();
            if (nativeWorldActor instanceof Mob) {
                Mob actingMob = (Mob) nativeWorldActor;
                out.nativeWorldActorKind = "MOB";
                out.nativeWorldActorEntityId = MultiplayerManager.getInstance().getServerEntityId(actingMob.id());
                out.nativeMobActorId = actingMob.id();
                out.nativeMobEntityId = out.nativeWorldActorEntityId;
            } else if (nativeWorldActor instanceof Buff
                    && ((Buff) nativeWorldActor).target instanceof Mob) {
                Mob targetMob = (Mob) ((Buff) nativeWorldActor).target;
                out.nativeWorldActorKind = "MOB_BUFF";
                out.nativeWorldActorEntityId = MultiplayerManager.getInstance().getServerEntityId(targetMob.id());
                out.nativeMobActorId = targetMob.id();
                out.nativeMobEntityId = out.nativeWorldActorEntityId;
            } else if (nativeWorldActor instanceof Blob) {
                out.nativeWorldActorKind = "BLOB";
            } else if ("MobSpawner".equals(nativeWorldActor.getClass().getSimpleName())) {
                out.nativeWorldActorKind = "RESPAWNER";
            } else {
                return null;
            }
            if (out.nativeWorldActorEntityId == null) out.nativeWorldActorEntityId = "";
            if (out.nativeMobEntityId == null) out.nativeMobEntityId = "";
        }
        for (int i = 0; i < level.length(); i++) {
            if (level.visited != null && level.visited[i]) out.visitedPositions.add(i);
            if (level.mapped != null && level.mapped[i]) out.mappedPositions.add(i);
        }

        for (int pos = 0; pos < level.length(); pos++) {
            Tile tile = new Tile();
            tile.pos = pos;
            tile.terrain = level.map[pos];
            tile.passable = level.passable[pos];
            tile.solid = level.solid[pos];
            tile.pit = level.pit[pos];
            tile.losBlocking = level.losBlocking[pos];
            tile.flammable = level.flamable[pos];
            tile.secret = level.secret[pos];
            tile.avoid = level.avoid[pos];
            tile.water = level.water[pos];
            tile.discoverable = level.discoverable[pos];
            tile.openSpace = level.openSpace[pos];
            out.tiles.add(tile);
        }

        if (level.transitions != null) {
            for (LevelTransition transition : level.transitions) {
                Transition t = new Transition();
                t.pos = transition.cell();
                t.type = transition.type == null ? "" : transition.type.name();
                t.targetDepth = transition.destDepth;
                t.targetBranch = transition.destBranch;
                t.targetType = transition.destType == null ? "" : transition.destType.name();
                out.transitions.add(t);
            }
        }

        if (level.mobs != null) {
            for (Mob mob : level.mobs) {
                MobData m = new MobData();
                m.mobId = mob.id();
                String serverEntityId = MultiplayerManager.getInstance().getServerEntityId(m.mobId);
                m.entityId = serverEntityId == null ? "" : serverEntityId;
                m.name = mob.getClass().getSimpleName();
                m.pos = mob.pos;
                m.hp = mob.HP;
                m.ht = mob.HT;
                m.shielding = Math.max(0, mob.shielding());
                m.state = mob.state == null ? "" : mob.state.getClass().getSimpleName();
                m.defenseSkill = mob.defenseSkill;
                m.baseSpeed = mob.multiplayerBaseSpeed();
                m.effectiveSpeed = mob.multiplayerEffectiveSpeed();
                m.cooldown = Math.max(0f, mob.cooldown());
                m.targetCell = mob.multiplayerTargetCell();
                m.targetType = mob.multiplayerTargetType();
                m.targetEntityId = mob.multiplayerTargetEntityId();
                m.enemySeen = mob.multiplayerEnemySeen();
                m.alerted = mob.multiplayerAlerted();
                m.serializedBundle = currentMobBundle(mob);
                for (Buff buff : mob.buffs()) {
                    BuffData buffData = new BuffData();
                    Bundle buffBundle = new Bundle();
                    buffBundle.put("buff", buff);
                    buffData.serializedBundle = buffBundle.toString();
                    buffData.cooldown = Math.max(0f, buff.cooldown());
                    m.buffs.add(buffData);
                }
                out.mobs.add(m);
            }
        }

        out.heaps = currentHeaps(level);
        if (level.traps != null) {
            for (Trap trap : level.traps.valueList()) {
                if (trap == null) continue;
                TrapData t = new TrapData();
                t.pos = trap.pos;
                t.className = trap.getClass().getName();
                t.active = trap.active;
                t.visible = trap.visible;
                t.reclaimed = trap.reclaimed;
                t.color = trap.color;
                t.shape = trap.shape;
                Bundle trapBundle = new Bundle();
                trapBundle.put("trap", trap);
                t.serializedBundle = trapBundle.toString();
                out.traps.add(t);
            }
        }
        if (level.blobs != null) {
            for (Blob blob : level.blobs.values()) {
                if (blob == null) continue;
                BlobData data = new BlobData();
                data.className = blob.getClass().getName();
                data.cooldown = Math.max(0f, blob.cooldown());
                Bundle blobBundle = new Bundle();
                blobBundle.put("blob", blob);
                data.serializedBundle = blobBundle.toString();
                out.blobs.add(data);
            }
        }
        if (level.plants != null) {
            for (Plant plant : level.plants.valueList()) {
                if (plant == null) continue;
                PlantData data = new PlantData();
                data.pos = plant.pos;
                data.className = plant.getClass().getName();
                Bundle plantBundle = new Bundle();
                plantBundle.put("plant", plant);
                data.serializedBundle = plantBundle.toString();
                out.plants.add(data);
            }
        }
        out.heroStateJson = currentHeroStateJson();
        return new Json().toJson(out);
    }

    /** Serializes native timed buffs after combat without reimplementing their effects remotely. */
    public static String currentCombatBuffsJson(Char character) {
        List<BuffData> out = new ArrayList<>();
        if (character != null) {
            for (Buff buff : character.buffs()) {
                if (buff == null) continue;
                BuffData data = new BuffData();
                Bundle buffBundle = new Bundle();
                buffBundle.put("buff", buff);
                data.serializedBundle = buffBundle.toString();
                data.cooldown = Math.max(0f, buff.cooldown());
                out.add(data);
            }
        }
        return new Json().toJson(out);
    }

    public static String currentHeapsJson() {
        return new Json().toJson(currentHeaps(Dungeon.level));
    }

    private static List<HeapData> currentHeaps(Level level) {
        List<HeapData> heaps = new ArrayList<>();
        if (level == null || level.heaps == null) return heaps;
        for (Heap heap : level.heaps.valueList()) {
            if (heap == null) continue;
            HeapData h = new HeapData();
            h.pos = heap.pos;
            h.type = heap.type == null ? "HEAP" : heap.type.name();
            h.seen = heap.seen;
            h.haunted = heap.haunted;
            h.hidden = heap.hidden;
            h.autoExplored = heap.autoExplored;
            for (Item item : heap.items) {
                if (item == null) continue;
                ItemData d = new ItemData();
                d.className = item.getClass().getName();
                d.quantity = item.quantity();
                d.level = item.level();
                d.cursed = item.cursed;
                d.cursedKnown = item.cursedKnown;
                Bundle itemBundle = new Bundle();
                itemBundle.put("item", item);
                d.serializedBundle = itemBundle.toString();
                h.items.add(d);
            }
            heaps.add(h);
        }
        return heaps;
    }

    /** Native Bundle serialization used for exact attack-weapon matching on the authority device. */
    public static String currentItemBundle(Item item) {
        if (item == null) return "";
        Bundle itemBundle = new Bundle();
        itemBundle.put("item", item);
        return itemBundle.toString();
    }

    /** Resolves only a weapon already present in the attacker's trusted restored belongings. */
    public static com.shatteredpixel.shatteredpixeldungeon.items.KindOfWeapon findOwnedAttackWeapon(
            com.shatteredpixel.shatteredpixeldungeon.actors.hero.Hero hero, String serializedBundle) {
        if (hero == null || hero.belongings == null || serializedBundle == null || serializedBundle.isEmpty()) return null;
        for (Item item : hero.belongings.getAllItems(Item.class)) {
            if (item instanceof com.shatteredpixel.shatteredpixeldungeon.items.KindOfWeapon
                    && serializedBundle.equals(currentItemBundle(item))) {
                return (com.shatteredpixel.shatteredpixeldungeon.items.KindOfWeapon) item;
            }
        }
        return null;
    }

    public static String currentHeroStateJson() {
        return currentHeroStateJson(Dungeon.hero);
    }

    /** Serializes the same native combat/inventory state contract for a remote hero replica. */
    public static String currentHeroStateJson(com.shatteredpixel.shatteredpixeldungeon.actors.hero.Hero hero) {
        if (hero == null) return "";
        Bundle heroState = new Bundle();
        Bundle nativeHero = new Bundle();
        hero.storeInBundle(nativeHero);
        heroState.put("combatBundle", nativeHero.toString());
        Bundle inventory = new Bundle();
        hero.belongings.storeInBundle(inventory);
        heroState.put("inventoryBundle", inventory.toString());
        heroState.put("hp", hero.HP);
        heroState.put("ht", hero.HT);
        heroState.put("pos", hero.pos);
        heroState.put("shielding", hero.shielding());
        heroState.put("rooted", hero.rooted);
        heroState.put("paralysed", hero.paralysed);
        // Notes and quest flags are run-global SPD state and must survive reconnects/floor swaps.
        // Never export a remote Hero's view as the device's shared journal.
        if (hero == Dungeon.hero) {
            Bundle notesBundle = new Bundle();
            com.shatteredpixel.shatteredpixeldungeon.journal.Notes.storeInBundle(notesBundle);
            heroState.put("notesBundle", notesBundle.toString());
            heroState.put("ironKeyCount", com.shatteredpixel.shatteredpixeldungeon.journal.Notes.keyCount(
                    new com.shatteredpixel.shatteredpixeldungeon.items.keys.IronKey(Dungeon.depth)));
            heroState.put("crystalKeyCount", com.shatteredpixel.shatteredpixeldungeon.journal.Notes.keyCount(
                    new com.shatteredpixel.shatteredpixeldungeon.items.keys.CrystalKey(Dungeon.depth)));
            heroState.put("wornKeyCount", com.shatteredpixel.shatteredpixeldungeon.journal.Notes.keyCount(
                    new com.shatteredpixel.shatteredpixeldungeon.items.keys.WornKey(Dungeon.depth)));
            heroState.put("goldenKeyCount", com.shatteredpixel.shatteredpixeldungeon.journal.Notes.keyCount(
                    new com.shatteredpixel.shatteredpixeldungeon.items.keys.GoldenKey(Dungeon.depth)));
            Bundle quests = new Bundle();
            com.shatteredpixel.shatteredpixeldungeon.actors.mobs.npcs.Ghost.Quest.storeInBundle(quests);
            com.shatteredpixel.shatteredpixeldungeon.actors.mobs.npcs.Wandmaker.Quest.storeInBundle(quests);
            com.shatteredpixel.shatteredpixeldungeon.actors.mobs.npcs.Blacksmith.Quest.storeInBundle(quests);
            com.shatteredpixel.shatteredpixeldungeon.actors.mobs.npcs.Imp.Quest.storeInBundle(quests);
            heroState.put("questStateBundle", quests.toString());
        }
        int ankhCount = 0;
        int blessedAnkhCount = 0;
        for (com.shatteredpixel.shatteredpixeldungeon.items.Ankh ankh
                : hero.belongings.getAllItems(com.shatteredpixel.shatteredpixeldungeon.items.Ankh.class)) {
            ankhCount++;
            if (ankh.isBlessed()) blessedAnkhCount++;
        }
        heroState.put("ankhCount", ankhCount);
        heroState.put("blessedAnkhCount", blessedAnkhCount);
        heroState.put("cooldown", Math.max(0f, hero.cooldown()));
        heroState.put("buffCount", hero.buffs().size());
        int buffIndex = 0;
        for (Buff buff : hero.buffs()) {
            Bundle buffBundle = new Bundle();
            buffBundle.put("buff", buff);
            heroState.put("buff_" + buffIndex, buffBundle.toString());
            heroState.put("buffCooldown_" + buffIndex, Math.max(0f, buff.cooldown()));
            buffIndex++;
        }
        return heroState.toString();
    }}