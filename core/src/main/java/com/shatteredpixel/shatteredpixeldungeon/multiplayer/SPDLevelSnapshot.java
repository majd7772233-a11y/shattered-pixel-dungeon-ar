package com.shatteredpixel.shatteredpixeldungeon.multiplayer;

import com.badlogic.gdx.utils.Json;
import com.shatteredpixel.shatteredpixeldungeon.Dungeon;
import com.shatteredpixel.shatteredpixeldungeon.actors.buffs.Buff;
import com.watabou.utils.Bundle;
import com.shatteredpixel.shatteredpixeldungeon.actors.mobs.Mob;
import com.shatteredpixel.shatteredpixeldungeon.items.Heap;
import com.shatteredpixel.shatteredpixeldungeon.items.Item;
import com.shatteredpixel.shatteredpixeldungeon.levels.traps.Trap;
import com.shatteredpixel.shatteredpixeldungeon.levels.Level;
import com.shatteredpixel.shatteredpixeldungeon.levels.features.LevelTransition;

import java.util.ArrayList;
import java.util.List;

/**
 * Wire representation of a level generated by the real SPD level-generation pipeline.
 * The client exports the generated world; the server validates and stores it rather
 * than attempting to reproduce SPD's Java RNG, builders, painters and room logic in TS.
 */
public final class SPDLevelSnapshot {
    public int schemaVersion = 1;
    public int depth;
    public int branch;
    public int width;
    public int height;
    public int entrancePos;
    public int exitPos;
    public long seed;
    public List<Tile> tiles = new ArrayList<>();
    public List<Transition> transitions = new ArrayList<>();
    public List<MobData> mobs = new ArrayList<>();
    public List<HeapData> heaps = new ArrayList<>();
    public List<TrapData> traps = new ArrayList<>();
    public String heroStateJson = "";

    public static final class Tile {
        public int pos;
        public int terrain;
        public boolean passable;
        public boolean solid;
        public boolean pit;
        public boolean losBlocking;
    }

    public static final class Transition {
        public int pos;
        public String type;
        public int targetDepth;
        public int targetBranch;
        public String targetType;
    }

    public static final class MobData {
        public int mobId;
        public String name;
        public int pos;
        public int hp;
        public int ht;
        public String state;
        public String serializedBundle = "";
        public int defenseSkill;
        public float baseSpeed;
        public float cooldown;
        public List<BuffData> buffs = new ArrayList<>();
    }

    public static final class BuffData {
        public String serializedBundle = "";
        public float cooldown;
    }

    public static final class ItemData {
        public String className;
        public int quantity;
        public int level;
        public boolean cursed;
        public boolean cursedKnown;
        public String serializedBundle = "";
    }

    public static final class HeapData {
        public int pos;
        public String type;
        public boolean seen;
        public boolean haunted;
        public boolean hidden;
        public List<ItemData> items = new ArrayList<>();
    }

    public static final class TrapData {
        public int pos;
        public String className;
        public boolean active;
        public boolean visible;
        public boolean reclaimed;
        public int color;
        public int shape;
        public String serializedBundle = "";
    }

    private SPDLevelSnapshot() {}

    public static String currentLevelJson() {
        Level level = Dungeon.level;
        if (level == null) return null;

        SPDLevelSnapshot out = new SPDLevelSnapshot();
        out.depth = Dungeon.depth;
        out.branch = Dungeon.branch;
        out.width = level.width();
        out.height = level.height();
        out.entrancePos = level.entrance();
        out.exitPos = level.exit();
        out.seed = Dungeon.seedCurDepth();

        for (int pos = 0; pos < level.length(); pos++) {
            Tile tile = new Tile();
            tile.pos = pos;
            tile.terrain = level.map[pos];
            tile.passable = level.passable[pos];
            tile.solid = level.solid[pos];
            tile.pit = level.pit[pos];
            tile.losBlocking = level.losBlocking[pos];
            out.tiles.add(tile);
        }

        if (level.transitions != null) {
            for (LevelTransition transition : level.transitions) {
                Transition t = new Transition();
                t.pos = transition.cell();
                t.type = transition.type == null ? "" : transition.type.name();
                t.targetDepth = transition.destDepth;
                t.targetBranch = transition.destBranch;
                t.targetType = transition.destType == null ? "" : transition.destType.name();
                out.transitions.add(t);
            }
        }

        if (level.mobs != null) {
            for (Mob mob : level.mobs) {
                MobData m = new MobData();
                m.mobId = mob.id();
                m.name = mob.getClass().getSimpleName();
                m.pos = mob.pos;
                m.hp = mob.HP;
                m.ht = mob.HT;
                m.state = mob.state == null ? "" : mob.state.getClass().getSimpleName();
                m.defenseSkill = mob.defenseSkill;
                m.baseSpeed = mob.multiplayerBaseSpeed();
                m.cooldown = Math.max(0f, mob.cooldown());
                Bundle mobBundle = new Bundle();
                mobBundle.put("mob", mob);
                m.serializedBundle = mobBundle.toString();
                for (Buff buff : mob.buffs()) {
                    BuffData buffData = new BuffData();
                    Bundle buffBundle = new Bundle();
                    buffBundle.put("buff", buff);
                    buffData.serializedBundle = buffBundle.toString();
                    buffData.cooldown = Math.max(0f, buff.cooldown());
                    m.buffs.add(buffData);
                }
                out.mobs.add(m);
            }
        }

        if (level.heaps != null) {
            for (Heap heap : level.heaps.valueList()) {
                if (heap == null) continue;
                HeapData h = new HeapData();
                h.pos = heap.pos;
                h.type = heap.type == null ? "HEAP" : heap.type.name();
                h.seen = heap.seen;
                h.haunted = heap.haunted;
                h.hidden = heap.hidden;
                for (Item item : heap.items) {
                    if (item == null) continue;
                    ItemData d = new ItemData();
                    d.className = item.getClass().getName();
                    d.quantity = item.quantity();
                    d.level = item.level();
                    d.cursed = item.cursed;
                    d.cursedKnown = item.cursedKnown;
                    Bundle itemBundle = new Bundle();
                    itemBundle.put("item", item);
                    d.serializedBundle = itemBundle.toString();
                    h.items.add(d);
                }
                out.heaps.add(h);
            }
        }
        if (level.traps != null) {
            for (Trap trap : level.traps.valueList()) {
                if (trap == null) continue;
                TrapData t = new TrapData();
                t.pos = trap.pos;
                t.className = trap.getClass().getName();
                t.active = trap.active;
                t.visible = trap.visible;
                t.reclaimed = trap.reclaimed;
                t.color = trap.color;
                t.shape = trap.shape;
                Bundle trapBundle = new Bundle();
                trapBundle.put("trap", trap);
                t.serializedBundle = trapBundle.toString();
                out.traps.add(t);
            }
        }
        out.heroStateJson = currentHeroStateJson();
        return new Json().toJson(out);
    }

    public static String currentHeroStateJson() {
        if (Dungeon.hero == null) return "";
        Bundle heroState = new Bundle();
        Bundle inventory = new Bundle();
        Dungeon.hero.belongings.storeInBundle(inventory);
        heroState.put("inventoryBundle", inventory.toString());
        heroState.put("hp", Dungeon.hero.HP);
        heroState.put("ht", Dungeon.hero.HT);
        heroState.put("pos", Dungeon.hero.pos);
        heroState.put("cooldown", Math.max(0f, Dungeon.hero.cooldown()));
        heroState.put("buffCount", Dungeon.hero.buffs().size());
        int buffIndex = 0;
        for (Buff buff : Dungeon.hero.buffs()) {
            Bundle buffBundle = new Bundle();
            buffBundle.put("buff", buff);
            heroState.put("buff_" + buffIndex, buffBundle.toString());
            heroState.put("buffCooldown_" + buffIndex, Math.max(0f, buff.cooldown()));
            buffIndex++;
        }
        return heroState.toString();
    }
}